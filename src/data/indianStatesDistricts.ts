/**
 * Returns the list of all 28 Indian States and 8 Union Territories in Hindi.
 */
export function getAllIndianStates(): string[] {
  return Object.keys(INDIAN_STATES_AND_DISTRICTS);
}

/**
 * Returns all districts for a given Indian State or Union Territory.
 */
export function getDistrictsForState(stateName: string): string[] {
  if (!stateName) return [];
  const clean = stateName.trim();
  if (INDIAN_STATES_AND_DISTRICTS[clean]) {
    return INDIAN_STATES_AND_DISTRICTS[clean];
  }
  // Fallback case-insensitive / partial match
  for (const [k, v] of Object.entries(INDIAN_STATES_AND_DISTRICTS)) {
    if (k.includes(clean) || clean.includes(k)) {
      return v;
    }
  }
  return [];
}

/**
 * Infers the Indian State/UT from a district name if already known.
 */
export function inferStateFromDistrict(districtName: string): string | null {
  if (!districtName) return null;
  const clean = districtName.trim().toLowerCase();
  for (const [state, districts] of Object.entries(INDIAN_STATES_AND_DISTRICTS)) {
    for (const d of districts) {
      if (d.toLowerCase() === clean || clean.includes(d.toLowerCase()) || d.toLowerCase().includes(clean)) {
        return state;
      }
    }
  }
  return null;
}

/**
 * Validates whether a district belongs to a specified state.
 */
export function isValidDistrict(stateName: string, districtName: string): boolean {
  const districts = getDistrictsForState(stateName);
  if (!districts || districts.length === 0) return false;
  const clean = districtName.trim().toLowerCase();
  return districts.some(d => d.toLowerCase() === clean);
}
