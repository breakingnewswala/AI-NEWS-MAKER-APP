export function filterActiveVideos(videos: VideoFeedItem[]): VideoFeedItem[] {
  return (videos || []).filter((v) => v && v.id);
}

export function filterActiveNews(posts: NewsFeedPost[]): NewsFeedPost[] {
  return (posts || []).filter((p) => p && p.id);
}

